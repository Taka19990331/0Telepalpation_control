function [d,c,ck] = validate(T,M,o)
c=qm.conditions(M);
assert(qm.textValue(M,'RESULT.status_name')=="COMPLETE",'RESULT status not COMPLETE');
assert(qm.textValue(M,'RESULT.errors')=="[]",'RESULT errors not empty');
assert(qm.number(M,'RESULT.rows')==height(T),'RESULT.rows disagrees with data');
% Check redundant settings independently of between-file comparison.
pairs={ 'SAMPLING_FREQUENCY_HZ (fs)','CONFIG.Hz',1; ...
    'SWEEP_DURATION_S (T)','CONFIG.Duration_s',1; ...
    'SWEEP_DURATION_S (T)','CONFIG.Sweep_us',1e-6; ...
    'PRE_HOLD_DURATION_S (T_pre)','CONFIG.PreHold_s',1; ...
    'PRE_HOLD_DURATION_S (T_pre)','CONFIG.Pre_us',1e-6; ...
    'PRE_HOLD_DURATION_S (T_pre)','CONFIG.Average_us',1e-6; ...
    'POST_HOLD_DURATION_S (T_post)','CONFIG.PostHold_s',1; ...
    'POST_HOLD_DURATION_S (T_post)','CONFIG.Post_us',1e-6; ...
    'START_FREQUENCY_HZ (f0)','CONFIG.F0_Hz',1; ...
    'END_FREQUENCY_HZ (f1)','CONFIG.F1_Hz',1; ...
    'START_AMPLITUDE_NM (A0)','CONFIG.A0_Nm',1; ...
    'END_AMPLITUDE_NM (A1)','CONFIG.A1_Nm',1; ...
    'AMPLITUDE_EXPONENT (a)','CONFIG.AmplitudeExponent',1; ...
    'KP_PD (Kp) [Nm/deg]','CONFIG.KP_Nm_per_deg',1; ...
    'KD_PD (Kd) [Nm/(rad/s)]','CONFIG.KD_Nm_per_rad_s',1; ...
    'REFERENCE_POSITION_DEG (theta_ref)','CONFIG.Hold_deg',1; ...
    'TORQUE_LIMIT_NM (tau_limit)','CONFIG.TorqueLimit_Nm',1};
for k=1:size(pairs,1)
    a=qm.number(M,pairs{k,1}); b=qm.number(M,pairs{k,2})*pairs{k,3};
    assert(abs(a-b)<=1e-8+1e-6*max(abs([a b])), ...
        'Inconsistent duplicate metadata: %s / %s',pairs{k,1},pairs{k,2});
end
assert(abs(qm.number(M,'CONFIG.Period_us')*1e-6*c.fs-1)<1e-6,'Period/fs mismatch');
assert(T.index(1)==0 && all(diff(T.phase)>=0),'Invalid phase/index order');
assert(all(T.can_tx_accepted==1) && all(T.motor_error==0),'CAN/motor fault');
assert(all(T.feedback_age_us*1e-6<c.feedbackTimeout),'Feedback timeout');
assert(all(diff(T.actual_us)<1.5e6/c.fs),'Missing control-time sample');
assert(sum(T.phase==0)>=round(c.preDuration*c.fs),'Insufficient initial averaging');
assert(sum(T.phase==0)==qm.number(M,'CONFIG.AverageRows'),'AverageRows mismatch');
assert(sum(T.phase==3)==1 && T.phase(end)==3,'Missing/extra final stop row');
assert(all(T.command_Nm(T.phase==3)==0),'Nonzero final stop command');
[d,ck]=qm.prepare(T,c,o);
end
